fn cp866_byte(c: char) -> Option<u8> {
    let code = c as u32;
    if code < 0x80 {
        return Some(code as u8);
    }
    CP866_HIGH.iter().position(|&x| x == c).map(|i| 0x80 + i as u8)
}

fn cp1251_char(b: u8) -> char {
    if b < 0x80 {
        b as char
    } else {
        CP1251_HIGH[(b - 0x80) as usize]
    }
}

/// Есть ли в строке псевдографика: она в обычном русском тексте не встречается,
/// а в cp1251→cp866 порче — почти всегда.
fn has_box_drawing(s: &str) -> bool {
    s.chars()
        .any(|c| (0x2500..=0x25FF).contains(&(c as u32)))
}

/// Портированная строка → исходная. `None` — порчи не видно или починить нельзя.
pub fn repair(s: &str) -> Option<String> {
    if !has_box_drawing(s) {
        return None;
    }
    let mut bytes = Vec::with_capacity(s.len());
    for c in s.chars() {
        bytes.push(cp866_byte(c)?);
    }
    let fixed: String = bytes.into_iter().map(cp1251_char).collect();
    let has_cyrillic = fixed
        .chars()
        .any(|c| ('\u{0400}'..='\u{04FF}').contains(&c) || c == '\u{00B1}');
    if has_cyrillic && fixed != s {
        Some(fixed)
    } else {
        None
    }
}

/// Починить, если видна порча; иначе вернуть как есть.
pub fn clean(s: &str) -> String {
    repair(s).unwrap_or_else(|| s.to_string())
}

/// Починить текст события и известные текстовые поля `meta`.
pub fn clean_event(ev: &mut crate::models::Event) {
    if let Some(text) = ev.text.as_mut() {
        let fixed = clean(text);
        *text = fixed;
    }
    if let Some(meta) = ev.meta.as_object_mut() {
        for key in ["window", "range", "state", "title", "name", "process"] {
            if let Some(serde_json::Value::String(value)) = meta.get_mut(key) {
                let fixed = clean(value);
                *value = fixed;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn repairs_cp1251_read_as_cp866() {
        // Строки-образцы сняты с реального журнала 20261122-183516-pcmflash.
        assert_eq!(clean("╚фхэЄшЇшърЎш\u{a0}"), "Идентификация");
        assert_eq!(clean("╫Єхэшх"), "Чтение");
        assert_eq!(clean("╟ряшё№"), "Запись");
        assert_eq!(clean("╤юїЁрэшЄ№ фрээ√х"), "Сохранить данные");
        assert_eq!(clean("▒6 V"), "±6 V");
    }

    #[test]
    fn leaves_normal_text_alone() {
        for s in ["Идентификация", "PCMflash [1.2.0]", "±6 V", "Да", ""] {
            assert_eq!(clean(s), s);
        }
    }

    #[test]
    fn event_text_and_window_are_repaired() {
        let mut ev = crate::models::Event::new(
            crate::models::EventKind::UiAction,
            crate::models::Transport::App,
            1.0,
            "",
        );
        ev.text = Some("╚фхэЄшЇшърЎш\u{a0}".into());
        ev.meta = serde_json::json!({"window": "PCMflash [1.2.0]", "range": "▒6 V"});
        clean_event(&mut ev);
        assert_eq!(ev.text.as_deref(), Some("Идентификация"));
        assert_eq!(ev.meta["range"], "±6 V");
        assert_eq!(ev.meta["window"], "PCMflash [1.2.0]");
    }
}
